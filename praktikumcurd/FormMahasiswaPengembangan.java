    // READ: tampilkan isi array ke tabel
    private void tampilkanData() {
        String kata = txtCari.getText().trim().toLowerCase();
        
        model.setRowCount(0);
        indeksTampil.clear();
        
        for (int i = 0; i < jumlah; i++) {
            if (dataMahasiswa[i][1].toLowerCase().contains(kata)) {
                model.addRow(dataMahasiswa[i]);
                indeksTampil.add(i);
            }
        }
    }
    // Cari posisi NIM di array, hasil -1 jika tidak ada
    private int cariIndeks(String nim) {
        for (int i = 0; i < jumlah; i++) {
            if (dataMahasiswa[i][0].equals(nim)) {
                return i;
            }
        }return -1;
    }
    
    private void cariData() {
    String keyword = txtCari.getText().trim().toLowerCase();

    model.setRowCount(0);
    indeksTampil.clear();

    for (int i = 0; i < jumlah; i++) {

        String nama = dataMahasiswa[i][1].toLowerCase();

        if (nama.contains(keyword)) {

            model.addRow(dataMahasiswa[i]);
            indeksTampil.add(i);

        }
    }

    if (indeksTampil.isEmpty()) {
        JOptionPane.showMessageDialog(
            this,
            "Data mahasiswa tidak ditemukan!"
        );
    }
}
    
    private String getJenisKelamin() {
        return rbLaki.isSelected() ? "Laki-laki" : "Perempuan";
    }
    private boolean inputValid() {
        if (inputNim.getText().trim().isEmpty()||
                inputNama.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "NIM dan Nama wajib diisi!","Peringatan",
                JOptionPane.WARNING_MESSAGE);
            return false;
        }
        return true;
    }
    private void bersihkanForm() {
        inputNim.setText("");
        inputNama.setText("");
        rbLaki.setSelected(true);
        cbProdi.setSelectedIndex(0);
        inputNim.setEditable(true);
        tblMahasiswa.clearSelection();
        inputNim.requestFocus();
        txtCari.setText("");
        tampilkanData();
    }
    private void tmblTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tmblTambahActionPerformed
        // TODO add your handling code here:
        if (!inputValid())
            return;
        
        String nim = inputNim.getText().trim();
        
        if (cariIndeks(nim) != -1) {
        JOptionPane.showMessageDialog(this, "NIM sudah terdaftar!");
        return;
    }
        if (jumlah >= MAKS) {
            JOptionPane.showMessageDialog(this, "Array sudah penuh! Maksimal " + MAKS + " data");
            return;
        }
        dataMahasiswa[jumlah][0] = nim;
        dataMahasiswa[jumlah][1] = inputNama.getText();
        dataMahasiswa[jumlah][2] = getJenisKelamin();
        dataMahasiswa[jumlah][3] = cbProdi.getSelectedItem().toString();
        
        jumlah++;
        
        tampilkanData();
        bersihkanForm();
    }//GEN-LAST:event_tmblTambahActionPerformed

    private void tmblUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tmblUbahActionPerformed
        // TODO add your handling code here:
         int baris = tblMahasiswa.getSelectedRow();
         
         if (baris == -1) {
             JOptionPane.showMessageDialog(this, "Pilih data di tabel terlebih dahulu!");
             return;
         }
         
         if (!inputValid())
             return;
         
         dataMahasiswa[baris][1] = inputNama.getText().trim();
         dataMahasiswa[baris][2] = getJenisKelamin();
         dataMahasiswa[baris][3] = cbProdi.getSelectedItem().toString();
         
         tampilkanData();
         bersihkanForm();
    }//GEN-LAST:event_tmblUbahActionPerformed

    private void tmblHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tmblHapusActionPerformed
        // TODO add your handling code here:
        int baris = tblMahasiswa.getSelectedRow();
        
        if (baris == -1) {
            JOptionPane.showMessageDialog(this, "Pilih data di tabel terlebih dahulu!");
            return;
        }
        
        int pilih = JOptionPane.showConfirmDialog(
                this, "Hapus data " + dataMahasiswa[baris][1] + "?", "Konfirmasi",
                JOptionPane.YES_NO_OPTION);
        
        if (pilih != JOptionPane.YES_OPTION) return;
        
        for (int i = baris; i < jumlah - 1; i++) {
            dataMahasiswa[i] = dataMahasiswa[i + 1];
        }
        
        dataMahasiswa[jumlah - 1] = new String[4];
        jumlah--;
        
        tampilkanData();
        bersihkanForm();
    }//GEN-LAST:event_tmblHapusActionPerformed

